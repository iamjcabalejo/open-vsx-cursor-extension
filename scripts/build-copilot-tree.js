/**
 * One-time migration: build workflow/copilot from .cursor content.
 * Run from repo root: node scripts/build-copilot-tree.js
 * After running, the Copilot adapter will copy from workflow/copilot only.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CURSOR = path.join(ROOT, ".cursor");
const COPILOT = path.join(ROOT, "workflow", "copilot");

function stripFrontmatter(content) {
  const match = content.match(/^---\r?\n[\s\S]*?\r?\n---\r?\n([\s\S]*)$/);
  return match ? match[1].trim() : content;
}

function rewriteToCopilot(content) {
  return content
    .replace(/\.cursor\/rules\//g, ".github/copilot-instructions.md and .github/instructions/")
    .replace(/\.cursor\/agents\//g, ".github/agents/")
    .replace(/\.cursor\/skills\//g, ".github/agents/ ")
    .replace(/\.cursor\/hooks\//g, ".github/workflows/")
    .replace(/\.cursor\/hooks\b/g, ".github/workflows")
    .replace(/\.cursor\//g, ".github/")
    .replace(/\.mdc\b/g, ".md");
}

const AGENT_SKILLS = {
  "backend-architect": ["api-design-patterns", "api-testing", "postgresql", "nosql-databases", "refactoring-checklist", "code-review"],
  "backend-reviewer": ["api-design-patterns", "api-testing", "code-review", "security-audit"],
  "frontend-architect": ["refactoring-checklist", "code-review", "accessibility-checklist", "performance-profiling", "e2e-playwright"],
  "frontend-reviewer": ["code-review", "accessibility-checklist", "performance-profiling", "e2e-playwright"],
  "database-expert": ["postgresql", "nosql-databases"],
  "refactoring-expert": ["refactoring-checklist"],
  "performance-engineer": ["performance-profiling"],
  "e2e-runner": ["e2e-playwright"],
  "security-engineer": ["security-audit"],
  "requirements-analyst": ["requirements-discovery"],
  "technical-writer": ["docs-structure"],
  "architecture-strategist": [],
  "system-architect": [],
  "pattern-recognition-specialist": [],
  "learning-guide": [],
  "deep-research-agent": [],
  "tech-stack-researcher": [],
};

function getSkillContent(skillName) {
  const skillPath = path.join(CURSOR, "skills", skillName, "SKILL.md");
  if (!fs.existsSync(skillPath)) return "";
  try {
    return stripFrontmatter(fs.readFileSync(skillPath, "utf-8"));
  } catch {
    return "";
  }
}

function buildInstructionsMd() {
  const rulesDir = path.join(CURSOR, "rules");
  const agentsDir = path.join(CURSOR, "agents");
  const parts = [
    "# Plan-Code-Review workflow (Plan → Code → Review/Test)",
    "",
    "Apply these rules and use the referenced agent perspectives when working in this repo.",
    "",
    "## Rules",
    "",
  ];
  if (fs.existsSync(rulesDir)) {
    const entries = fs.readdirSync(rulesDir, { withFileTypes: true });
    for (const e of entries) {
      if (!e.isFile() || (!e.name.endsWith(".mdc") && !e.name.endsWith(".md"))) continue;
      if (e.name === "README.md") continue;
      const raw = fs.readFileSync(path.join(rulesDir, e.name), "utf-8");
      parts.push("### " + e.name.replace(/\.(mdc|md)$/, "").replace(/-/g, " "));
      parts.push("");
      parts.push(rewriteToCopilot(stripFrontmatter(raw)));
      parts.push("");
    }
  }
  parts.push("## Agent roles (apply when relevant)");
  parts.push("");
  if (fs.existsSync(agentsDir)) {
    const files = fs.readdirSync(agentsDir).filter((f) => f.endsWith(".md"));
    for (const f of files) {
      const raw = fs.readFileSync(path.join(agentsDir, f), "utf-8");
      const nameMatch = raw.match(/name:\s*(\S+)/);
      const descMatch = raw.match(/description:\s*(.+)/);
      const name = nameMatch ? nameMatch[1] : f.replace(".md", "");
      const desc = descMatch ? descMatch[1].trim() : "";
      parts.push(`- **${name}**: ${desc}`);
    }
  }
  parts.push("");
  parts.push("---");
  parts.push("*Generated by Plan-Code-Review Workflow extension for GitHub Copilot.*");
  return parts.join("\n");
}

function buildAgentContentWithSkills(agentContent, agentBaseName) {
  const rewrittenAgent = rewriteToCopilot(agentContent);
  const skillNames = AGENT_SKILLS[agentBaseName];
  if (!skillNames || skillNames.length === 0) {
    return (
      rewrittenAgent +
      "\n\n---\n\n## Skills (for GitHub Copilot)\n\nNo additional skills defined for this agent; apply the compounding dev cycle and project rules.\n"
    );
  }
  const parts = [
    rewrittenAgent,
    "",
    "---",
    "",
    "## Skills (inlined for GitHub Copilot)",
    "",
    "GitHub Copilot does not load skills separately. The following skills apply to this agent; apply them when acting as this agent.",
    "",
  ];
  for (const skillName of skillNames) {
    const content = getSkillContent(skillName);
    if (!content) continue;
    parts.push("### " + skillName);
    parts.push("");
    parts.push(rewriteToCopilot(content));
    parts.push("");
  }
  return parts.join("\n");
}

function buildAgentsMd() {
  const agentsDir = path.join(CURSOR, "agents");
  const parts = [
    "# AGENTS.md — Compounding dev cycle and custom agents",
    "",
    "**All custom agents and work in this repo MUST follow the compounding development cycle** (Plan → Code → Review/Test → Plan).",
    "",
    "**Full cycle:** See **`.github/instructions/compounding-dev-cycle.instructions.md`** (path-specific instructions with `applyTo: \"**\"`; Copilot uses it together with this file and `.github/copilot-instructions.md`).",
    "",
    "---",
    "",
    "## Custom agents (GitHub Copilot)",
    "",
    "Custom agents are stored as `<name>.agent.md` under **`.github/agents/`**. When adding or editing agents:",
    "",
    "1. Create or update files in **`.github/agents/`** with the naming convention **`<name>.agent.md`**.",
    "2. **Always follow the compounding dev cycle** (Plan → Code → Review/Test → Plan); see `.github/instructions/compounding-dev-cycle.instructions.md`.",
    "3. Each agent definition should reference this cycle and produce handoff artifacts (plan doc, implementation notes, rework list) so the next phase or agent can continue without loss of context.",
    "4. **Skills**: Because GitHub Copilot does not load skills separately, each `.github/agents/<name>.agent.md` file includes **inlined skills** (checklists, patterns, and criteria for that agent). When acting as an agent, apply the skills section at the bottom of its file.",
    "",
    "**Repository layout for GitHub Copilot:**",
    "",
    "- **`.github/agents/`** — Custom agents (`<name>.agent.md`); follow compounding dev cycle.",
    "- **`.github/copilot-instructions.md`** — Rules and agent roles (project-wide instructions).",
    "- **`.github/instructions/compounding-dev-cycle.instructions.md`** — Compounding dev cycle (path-specific, applies to all files).",
    "- **`.github/workflows/`** — Hooks (hooks.json, README, scripts for session/audit/format).",
    "- **`.github/ISSUE_TEMPLATE/`** — Structured prompts (feature, bug report, review request) for the Plan phase.",
    "",
  ];
  if (fs.existsSync(agentsDir)) {
    const files = fs.readdirSync(agentsDir).filter((f) => f.endsWith(".md"));
    if (files.length > 0) {
      parts.push("**Agent files in this workspace** (`.github/agents/*.agent.md`):");
      parts.push("");
      for (const f of files) {
        const baseName = f.replace(".md", "");
        const raw = fs.readFileSync(path.join(agentsDir, f), "utf-8");
        const nameMatch = raw.match(/name:\s*(\S+)/);
        const descMatch = raw.match(/description:\s*(.+)/);
        const name = nameMatch ? nameMatch[1] : baseName;
        const desc = descMatch ? descMatch[1].trim() : "";
        parts.push(`- **${name}** (${baseName}.agent.md): ${desc}`);
      }
      parts.push("");
    }
  }
  parts.push("---");
  parts.push("*Generated by Plan-Code-Review Workflow extension for GitHub Copilot.*");
  return parts.join("\n");
}

function main() {
  if (!fs.existsSync(CURSOR)) {
    console.error("Run from repo root. .cursor not found.");
    process.exit(1);
  }

  const cyclePath = path.join(CURSOR, "rules", "compounding-dev-cycle.mdc");
  const cycleRaw = fs.existsSync(cyclePath)
    ? fs.readFileSync(cyclePath, "utf-8")
    : "# Compounding Development Cycle\n\nFollow **Plan → Code → Review/Test → Plan** for every feature or change.";
  const cycleBody = stripFrontmatter(cycleRaw);

  fs.mkdirSync(path.join(COPILOT, "instructions"), { recursive: true });
  fs.mkdirSync(path.join(COPILOT, "agents"), { recursive: true });
  fs.mkdirSync(path.join(COPILOT, "workflows"), { recursive: true });
  fs.mkdirSync(path.join(COPILOT, "ISSUE_TEMPLATE"), { recursive: true });

  fs.writeFileSync(
    path.join(COPILOT, "copilot-instructions.md"),
    buildInstructionsMd(),
    "utf-8"
  );

  const cycleInstructions = [
    "---",
    'applyTo: "**"',
    "---",
    "",
    rewriteToCopilot(cycleBody),
    "",
  ].join("\n");
  fs.writeFileSync(
    path.join(COPILOT, "instructions", "compounding-dev-cycle.instructions.md"),
    cycleInstructions,
    "utf-8"
  );

  const agentsDir = path.join(CURSOR, "agents");
  if (fs.existsSync(agentsDir)) {
    const files = fs.readdirSync(agentsDir).filter((f) => f.endsWith(".md"));
    for (const f of files) {
      const baseName = f.replace(".md", "");
      const agentContent = fs.readFileSync(path.join(agentsDir, f), "utf-8");
      const contentWithSkills = buildAgentContentWithSkills(agentContent, baseName);
      fs.writeFileSync(
        path.join(COPILOT, "agents", `${baseName}.agent.md`),
        contentWithSkills,
        "utf-8"
      );
    }
  }

  fs.writeFileSync(path.join(COPILOT, "AGENTS.md"), buildAgentsMd(), "utf-8");

  function buildSkillsSection() {
    const skillsDir = path.join(CURSOR, "skills");
    const parts = ["## Skills (use when relevant)", ""];
    if (!fs.existsSync(skillsDir)) return parts.join("\n");
    const entries = fs.readdirSync(skillsDir, { withFileTypes: true });
    for (const e of entries) {
      if (!e.isDirectory()) continue;
      const skillMdPath = path.join(skillsDir, e.name, "SKILL.md");
      if (!fs.existsSync(skillMdPath)) continue;
      const raw = fs.readFileSync(skillMdPath, "utf-8");
      const nameMatch = raw.match(/name:\s*(\S+)/);
      const descMatch = raw.match(/description:\s*(.+)/);
      const name = nameMatch ? nameMatch[1] : e.name;
      const desc = descMatch ? descMatch[1].trim() : "";
      parts.push(`- **${name}**: ${desc}`);
    }
    parts.push("");
    return parts.join("\n");
  }

  const userLevelContent = [buildInstructionsMd().trimEnd(), "", "---", "", buildSkillsSection().trimEnd(), ""].join("\n");
  fs.writeFileSync(path.join(COPILOT, "user-instructions.md"), userLevelContent, "utf-8");

  const hooksJsonPath = path.join(CURSOR, "hooks.json");
  if (fs.existsSync(hooksJsonPath)) {
    const parsed = JSON.parse(fs.readFileSync(hooksJsonPath, "utf-8"));
    const hooks = parsed?.hooks ?? {};
    const rewritten = {};
    const scriptNames = ["format.sh", "audit.sh", "session-init.sh"];
    for (const [event, entries] of Object.entries(hooks)) {
      const arr = Array.isArray(entries) ? entries : [];
      rewritten[event] = arr.map((e) => {
        const cmd = (e && typeof e === "object" && e.command) || "";
        const name = path.basename(cmd);
        const newCmd = scriptNames.includes(name) ? ".github/workflows/" + name : cmd;
        return { ...e, command: newCmd };
      });
    }
    fs.writeFileSync(
      path.join(COPILOT, "workflows", "hooks.json"),
      JSON.stringify({ hooks: rewritten }, null, 2),
      "utf-8"
    );
  }

  const hooksReadmePath = path.join(CURSOR, "hooks", "README.md");
  if (fs.existsSync(hooksReadmePath)) {
    const readme = fs.readFileSync(hooksReadmePath, "utf-8");
    fs.writeFileSync(
      path.join(COPILOT, "workflows", "README.md"),
      rewriteToCopilot(readme),
      "utf-8"
    );
  }

  const scriptNames = ["format.sh", "audit.sh", "session-init.sh"];
  const cursorHooksDir = path.join(CURSOR, "hooks");
  for (const name of scriptNames) {
    const src = path.join(cursorHooksDir, name);
    if (fs.existsSync(src)) {
      const content = fs.readFileSync(src, "utf-8");
      fs.writeFileSync(
        path.join(COPILOT, "workflows", name),
        rewriteToCopilot(content),
        "utf-8"
      );
    }
  }

  const issueTemplates = [
    { name: "feature.md", content: `---
name: Feature (structured prompt)
description: New feature or enhancement — use as structured prompt for Plan phase
title: "[Feature] "
labels: ["enhancement", "plan"]
assignees: []
---

## Goal
<!-- What should this feature achieve? -->

## Scope
- **In scope:**
- **Out of scope:**

## Acceptance criteria
- [ ] 
- [ ] 

## Technical approach (optional)
<!-- APIs, data model, key components -->

## Notes
<!-- Links, references, constraints. Follow Plan → Code → Review/Test → Plan (see AGENTS.md). -->
` },
    { name: "bug_report.md", content: `---
name: Bug report (structured prompt)
description: Report a bug — use as structured prompt for reproduction and fix
title: "[Bug] "
labels: ["bug"]
assignees: []
---

## Summary
<!-- Brief description of the bug -->

## Steps to reproduce
1. 
2. 
3. 

## Expected behavior
<!-- What should happen -->

## Actual behavior
<!-- What actually happens -->

## Environment (optional)
<!-- OS, runtime, versions -->

## Notes
<!-- Follow Plan → Code → Review/Test → Plan; fix should have tests and implementation notes (see AGENTS.md). -->
` },
    { name: "review_request.md", content: `---
name: Review request (structured prompt)
description: Request code review — structured prompt for Review/Test phase
title: "[Review] "
labels: ["review"]
assignees: []
---

## What changed
<!-- Summary of changes; link to plan or PR -->

## Plan / acceptance criteria
<!-- Link to plan doc or list AC this change implements -->

## Review focus (optional)
<!-- API contract, security, a11y, tests, etc. -->

## Notes
<!-- Reviewers: produce review summary, rework list (file/line + change + severity), test status. See AGENTS.md and .github/agents/ for reviewer agents. -->
` },
  ];
  for (const t of issueTemplates) {
    fs.writeFileSync(path.join(COPILOT, "ISSUE_TEMPLATE", t.name), t.content, "utf-8");
  }

  console.log("workflow/copilot built from .cursor");
}

main();
